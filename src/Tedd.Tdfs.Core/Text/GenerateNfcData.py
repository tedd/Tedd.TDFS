# Generates NfcData.g.cs (canonical combining classes, canonical decompositions and primary composites) from
# the Unicode Character Database bundled with CPython (unicodedata). The Unicode version is pinned by whichever
# Python generated the committed file (see UnicodeVersion in NfcData.g.cs); change it only deliberately, since name
# identity (NFC) of stored paths depends on it.
#
# Usage: python GenerateNfcData.py NfcData.g.cs

import unicodedata, sys
ud = unicodedata
ver = ud.unidata_version
ccc = []
decomp = []  # (cp, [full NFD cps])
comp = []    # (first, second, composite)
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF: continue
    ch = chr(cp)
    c = ud.combining(ch)
    if c: ccc.append((cp, c))
    if 0xAC00 <= cp <= 0xD7A3: continue  # Hangul syllables handled algorithmically
    d = ud.decomposition(ch)
    if d and not d.startswith('<'):
        full = [ord(x) for x in ud.normalize('NFD', ch)]
        decomp.append((cp, full))
        parts = [int(x, 16) for x in d.split()]
        if len(parts) == 2 and ud.normalize('NFC', ch) == ch:
            comp.append((parts[0], parts[1], cp))
# sanity: composition pairs unique
keys = {}
for a,b,c in comp:
    assert (a,b) not in keys, (a,b)
    keys[(a,b)] = c
comp.sort()
maxlen = max(len(f) for _,f in decomp)
pool = []
dindex = []
for cp, full in decomp:
    dindex.append((cp, len(pool), len(full)))
    pool.extend(full)
assert len(pool) < (1 << 20) and maxlen < 16

def emit_array(name, typ, vals, per=12, fmt="0x{:X}"):
    out = [f"    private static ReadOnlySpan<{typ}> {name} =>\n    ["]
    for i in range(0, len(vals), per):
        out.append("        " + ", ".join(fmt.format(v) for v in vals[i:i+per]) + ",")
    out.append("    ];")
    return "\n".join(out)

lines = []
lines.append("// <auto-generated>")
lines.append(f"// Generated from the Unicode Character Database {ver} (Python unicodedata). Do not edit by hand.")
lines.append("// Regenerate with Text/GenerateNfcData.py only when the pinned Unicode version is deliberately changed.")
lines.append("// </auto-generated>")
lines.append("")
lines.append("namespace Tedd.Tdfs.Text;")
lines.append("")
lines.append("internal static partial class Nfc")
lines.append("{")
lines.append(f"    /// <summary>Version of the Unicode Character Database the normalization tables were generated from.</summary>")
lines.append(f"    public const string UnicodeVersion = \"{ver}\";")
lines.append("")
lines.append("    // Code points with a non-zero canonical combining class, packed as (codePoint << 8) | ccc, ascending.")
lines.append(emit_array("CombiningClassData", "uint", [(cp << 8) | c for cp, c in ccc]))
lines.append("")
lines.append("    // Code points with a canonical decomposition (Hangul syllables excluded), ascending.")
lines.append(emit_array("DecompositionKeys", "uint", [cp for cp,_,_ in dindex]))
lines.append("")
lines.append("    // Parallel to DecompositionKeys: (offset << 4) | length into DecompositionPool (full NFD of the code point).")
lines.append(emit_array("DecompositionIndex", "uint", [(off << 4) | ln for _,off,ln in dindex]))
lines.append("")
lines.append("    // Concatenated full canonical decompositions.")
lines.append(emit_array("DecompositionPool", "uint", pool))
lines.append("")
lines.append("    // Primary composites keyed by ((ulong)first << 21) | second, ascending.")
lines.append(emit_array("CompositionKeys", "ulong", [(a << 21) | b for a,b,_ in comp], per=8))
lines.append("")
lines.append("    // Parallel to CompositionKeys: the primary composite code point.")
lines.append(emit_array("CompositionValues", "uint", [c for _,_,c in comp]))
lines.append("}")
with open(sys.argv[1], "w", newline="\r\n", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(len(ccc), len(decomp), len(pool), len(comp), maxlen, ver)
